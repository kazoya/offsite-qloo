/**
 * Real coverage probe against the Qloo hackathon API.
 * Usage: npm run probe   (needs QLOO_API_KEY in .env)
 * Writes docs/QLOO_COVERAGE.md with AGGREGATE numbers only (no Qloo entity data: their terms forbid
 * publishing response data in a public repository) and a raw summary in .cache/coverage.json.
 */
import { promises as fs } from "node:fs";
import { QlooClient, ACTIVITIES, CITIES as CITY_PROFILES, CUISINES, DIETARY, cityProfile, type QlooPlace } from "../src/connectors/qloo";

const ARABIC = /[\u0600-\u06FF]/;
const CITIES = CITY_PROFILES.map((c) => c.name);
const POOL = CUISINES.map((c) => c.tag);

const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${Math.round((100 * n) / d)}%`);

interface CityReport {
  city: string;
  localityMatched: string | null;
  destinationFound: boolean;
  restaurants: {
    returned: number;
    withPrice: number;
    withRating: number;
    arabicName: number;
    withDietaryTag: Record<string, number>;
    withHours: number;
    closed: number;
    withAffinityUnderSignal: number;
    signalReturned: number;
    explainabilityPresent: boolean;
  };
  activities: Record<string, number>;
  durationMs: number;
}

async function probeCity(qloo: QlooClient, city: string): Promise<CityReport> {
  const t0 = Date.now();
  const dest = await qloo.searchEntities({ query: city, types: ["urn:entity:destination"], take: 3 });
  const base = await qloo.insights({
    filterType: "urn:entity:place",
    locationQuery: cityProfile(city).qlooQuery,
    filterTags: POOL,
    take: 50,
  });
  // Same pool but with taste signals (3 cuisines + one artist entity) to measure affinity / explainability.
  const artist = (await qloo.searchEntities({ query: "Fairuz", types: ["urn:entity:artist"], take: 1 }))[0];
  const sig = await qloo.insights({
    filterType: "urn:entity:place",
    locationQuery: cityProfile(city).qlooQuery,
    filterTags: POOL,
    signalTags: [CUISINES[1]!.tag, CUISINES[6]!.tag, CUISINES[8]!.tag],
    signalEntities: artist ? [artist.entityId] : [],
    explainability: true,
    take: 20,
  });
  const places: QlooPlace[] = base.places;
  const dietary: Record<string, number> = {};
  for (const d of DIETARY) dietary[d.key] = places.filter((p) => p.tags.some((t) => t.id === d.tag)).length;

  const activities: Record<string, number> = {};
  for (const a of ACTIVITIES) {
    const r = await qloo.insights({
      filterType: "urn:entity:place",
      locationQuery: cityProfile(city).qlooQuery,
      filterTags: [a.tag],
      take: 20,
    });
    activities[a.key] = r.places.length;
  }
  return {
    city,
    localityMatched: base.locality ?? null,
    destinationFound: dest.length > 0,
    restaurants: {
      returned: places.length,
      withPrice: places.filter((p) => p.priceLevel !== undefined).length,
      withRating: places.filter((p) => p.rating !== undefined).length,
      arabicName: places.filter((p) => ARABIC.test(p.name)).length,
      withDietaryTag: dietary,
      withHours: places.filter((p) => p.hours && Object.keys(p.hours).length > 0).length,
      closed: places.filter((p) => p.isClosed).length,
      withAffinityUnderSignal: sig.places.filter((p) => p.affinity !== undefined).length,
      signalReturned: sig.places.length,
      explainabilityPresent: sig.places.some((p) => p.explain.length > 0),
    },
    activities,
    durationMs: Date.now() - t0,
  };
}

async function main() {
  const qloo = QlooClient.fromEnv();
  const reports: CityReport[] = [];
  for (const c of CITIES) {
    process.stderr.write(`probing ${c}...\n`);
    reports.push(await probeCity(qloo, c));
  }
  await fs.mkdir(".cache", { recursive: true });
  await fs.writeFile(".cache/coverage.json", JSON.stringify(reports, null, 2));

  const lines: string[] = [];
  lines.push("# Qloo coverage probe");
  lines.push("");
  lines.push(
    `Generated by \`npm run probe\` on ${new Date().toLocaleDateString("en-CA", { timeZone: "Asia/Amman" })} against the hackathon API ` +
      "(`https://hackathon.api.qloo.com`). Numbers are aggregates only; no Qloo entity data is stored in this repo.",
  );
  lines.push("");
  lines.push("## Restaurants (pool = union of 23 cuisine tags, `take=50`)");
  lines.push("");
  lines.push("| City | Locality matched | Venues | price_level | rating | Arabic name | hours | halal tag | vegetarian tag | vegan tag | gluten-free tag |");
  lines.push("|---|---|---|---|---|---|---|---|---|---|---|");
  for (const r of reports) {
    const x = r.restaurants;
    lines.push(
      `| ${r.city} | ${r.localityMatched ?? "-"} | ${x.returned} | ${pct(x.withPrice, x.returned)} | ${pct(x.withRating, x.returned)} | ${pct(x.arabicName, x.returned)} | ${pct(x.withHours, x.returned)} | ${pct(x.withDietaryTag.halal ?? 0, x.returned)} | ${pct(x.withDietaryTag.vegetarian ?? 0, x.returned)} | ${pct(x.withDietaryTag.vegan ?? 0, x.returned)} | ${pct(x.withDietaryTag.gluten_free ?? 0, x.returned)} |`,
    );
  }
  lines.push("");
  lines.push("## Taste signals (3 cuisine tags + 1 artist entity, `feature.explainability=true`)");
  lines.push("");
  lines.push("| City | Results | With affinity score | Explainability present |");
  lines.push("|---|---|---|---|");
  for (const r of reports) {
    const x = r.restaurants;
    lines.push(`| ${r.city} | ${x.signalReturned} | ${x.withAffinityUnderSignal} | ${x.explainabilityPresent ? "yes" : "no"} |`);
  }
  lines.push("");
  lines.push("## Activities (venues returned per category, `take=20`)");
  lines.push("");
  lines.push(`| Category | ${CITIES.join(" | ")} |`);
  lines.push(`|---|${CITIES.map(() => "---").join("|")}|`);
  for (const a of ACTIVITIES) {
    lines.push(`| ${a.en} | ${reports.map((r) => r.activities[a.key] ?? 0).join(" | ")} |`);
  }
  lines.push("");
  await fs.mkdir("docs", { recursive: true });
  const notes = await fs.readFile("docs/coverage-notes.md", "utf8").catch(() => "");
  await fs.writeFile("docs/QLOO_COVERAGE.md", lines.join("\n") + "\n" + notes);
  console.log(lines.join("\n"));
  console.log(`\nHTTP calls: ${qloo.httpCalls}, cache hits: ${qloo.cacheHits}`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
